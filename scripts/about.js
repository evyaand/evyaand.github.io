function showView(view) {
  const copy =
    VIEW_COPY[view];

  eyebrow.textContent =
    copy.eyebrow;

  title.textContent =
    copy.title;

  lede.textContent =
    copy.lede;

  navigation
    .querySelectorAll(
      "button[data-view]"
    )
    .forEach(
      (button) => {
        const active =
          button.dataset
            .view ===
          view;

        button.classList.toggle(
          "is-active",
          active
        );

        button.setAttribute(
          "aria-pressed",
          String(active)
        );
      }
    );

  if (
    view === "explore"
  ) {
    renderExplore(
      aboutView
    );
  }

  if (
    view === "nodes"
  ) {
    renderNodes(
      aboutView
    );
  }

  if (
    view === "origins"
  ) {
    renderOrigins(
      aboutView
    );
  }
}

function getViewFromHash() {
  const view =
    window.location.hash.replace(
      "#",
      ""
    );

  return VIEW_COPY[view]
    ? view
    : "explore";
}

navigation.addEventListener(
  "click",
  (event) => {
    const button =
      event.target.closest(
        "button[data-view]"
      );

    if (!button) {
      return;
    }

    const view =
      button.dataset.view;

    if (
      view === "explore"
    ) {
      history.pushState(
        null,
        "",
        window.location.pathname
      );
    } else {
      history.pushState(
        null,
        "",
        `#${view}`
      );
    }

    showView(view);
  }
);

window.addEventListener(
  "hashchange",
  () => {
    showView(
      getViewFromHash()
    );
  }
);

showView(
  getViewFromHash()
);
