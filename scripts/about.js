function activateGallery(
  storyElement,
  entry
) {
  if (
    !storyElement ||
    !entry.images ||
    entry.images.length < 2
  ) {
    return;
  }

  let activeIndex = 0;
  let touchStartX = null;

  const imageElement =
    storyElement.querySelector(
      ".about-gallery img"
    );

  const captionLink =
    storyElement.querySelector(
      "figcaption a"
    );

  const dots =
    storyElement.querySelector(
      ".about-gallery-dots"
    );

  const gallery =
    storyElement.querySelector(
      ".about-gallery"
    );

  dots.innerHTML =
    entry.images
      .map(
        (image, index) => `
          <button
            class="${index === 0
            ? "is-active"
            : ""
          }"
            type="button"
            data-image-index="${index}"
            aria-label="Photograph ${index + 1
          } of ${entry.images.length
          }"
            aria-pressed="${index === 0
          }"
          ></button>
        `
      )
      .join("");

  function showImage(index) {
    activeIndex =
      (
        index +
        entry.images.length
      ) %
      entry.images.length;

    const image =
      entry.images[
      activeIndex
      ];

    imageElement.className =
      image.className;

    imageElement.src =
      image.src;

    imageElement.alt =
      image.alt;

    captionLink.href =
      image.creditUrl;

    captionLink.textContent =
      image.credit;

    dots
      .querySelectorAll(
        "button"
      )
      .forEach(
        (
          button,
          buttonIndex
        ) => {
          const active =
            buttonIndex ===
            activeIndex;

          button.classList.toggle(
            "is-active",
            active
          );

          button.setAttribute(
            "aria-pressed",
            String(active)
          );
        }
      );
  }

  storyElement
    .querySelector(
      ".about-gallery-prev"
    )
    .addEventListener(
      "click",
      () => {
        showImage(
          activeIndex - 1
        );
      }
    );

  storyElement
    .querySelector(
      ".about-gallery-next"
    )
    .addEventListener(
      "click",
      () => {
        showImage(
          activeIndex + 1
        );
      }
    );

  dots.addEventListener(
    "click",
    (event) => {
      const button =
        event.target.closest(
          "button[data-image-index]"
        );

      if (!button) {
        return;
      }

      showImage(
        Number(
          button.dataset
            .imageIndex
        )
      );
    }
  );

  gallery.addEventListener(
    "touchstart",
    (event) => {
      touchStartX =
        event.touches[0]
          ?.clientX ?? null;
    },
    {
      passive: true,
    }
  );

  gallery.addEventListener(
    "touchend",
    (event) => {
      if (
        touchStartX === null
      ) {
        return;
      }

      const distance =
        event.changedTouches[0]
          .clientX -
        touchStartX;

      if (
        Math.abs(distance) >
        42
      ) {
        showImage(
          activeIndex +
          (
            distance < 0
              ? 1
              : -1
          )
        );
      }

      touchStartX = null;
    },
    {
      passive: true,
    }
  );
}

