function buildVisualEdges() {
  const seen = new Set();
  const edges = [];

  function add(
    fromId,
    toId,
    kind
  ) {
    const key = [
      fromId,
      toId,
    ]
      .sort()
      .join("::");

    if (seen.has(key)) {
      return;
    }

    seen.add(key);

    edges.push({
      fromId,
      toId,
      kind,
    });
  }

  STORY_EDGES.forEach(
    ([fromId, toId]) => {
      add(
        fromId,
        toId,
        "story"
      );
    }
  );

  INDEX_ENTRIES.forEach(
    (entry) => {
      INDEX_ENTRIES
        .filter(
          (candidate) =>
            candidate.id !==
            entry.id
        )
        .map(
          (candidate) => ({
            id: candidate.id,

            distance:
              Math.hypot(
                candidate.x -
                entry.x,
                candidate.y -
                entry.y
              ),
          })
        )
        .sort(
          (a, b) =>
            a.distance -
            b.distance
        )
        .slice(0, 2)
        .forEach(
          (neighbor) => {
            add(
              entry.id,
              neighbor.id,
              "proximity"
            );
          }
        );
    }
  );

  Object.entries(
    NODE_CHILDREN
  ).forEach(
    ([parentId, entries]) => {
      entries.forEach(
        (entry) => {
          add(
            parentId,
            entry.id,
            "branch"
          );
        }
      );
    }
  );

  return edges;
}

