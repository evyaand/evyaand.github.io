function renderNodes(
  container
) {
  let activeId =
    "statute-of-liberty";

  let pan = {
    x: 0,
    y: 0,
  };

  let drag = null;

  let suppressClick =
    false;

  let branchAnimationRunning =
    false;

  const expandedNodes =
    new Set();

  const visualEdges =
    buildVisualEdges();

  container.className =
    "about-view about-graph-view";

  container.innerHTML = `
    <div
      class="life-graph"
      aria-label="Interactive map of places, roles and turning points"
    >
      <div
        class="life-graph-world"
      >
        <svg
          class="life-graph-lines"
          viewBox="0 0 100 100"
          preserveAspectRatio="none"
          aria-hidden="true"
        ></svg>

        <div
          class="life-graph-nodes"
        ></div>
      </div>

      <p
        class="life-graph-hint"
      >
        Drag to explore · select a node to focus
      </p>
    </div>

    <div
      class="about-story-slot"
    ></div>
  `;

  const graph =
    container.querySelector(
      ".life-graph"
    );

  const world =
    container.querySelector(
      ".life-graph-world"
    );

  const lines =
    container.querySelector(
      ".life-graph-lines"
    );

  const nodes =
    container.querySelector(
      ".life-graph-nodes"
    );

  const storySlot =
    container.querySelector(
      ".about-story-slot"
    );

  function visibleEntries() {
    const visible = [
      ...INDEX_ENTRIES,
    ];

    function appendChildren(
      parentId
    ) {
      if (
        !expandedNodes.has(
          parentId
        )
      ) {
        return;
      }

      childrenOf(
        parentId
      ).forEach(
        (entry) => {
          visible.push(
            entry
          );

          appendChildren(
            entry.id
          );
        }
      );
    }

    INDEX_ENTRIES.forEach(
      (entry) => {
        appendChildren(
          entry.id
        );
      }
    );

    return visible;
  }

  function visibleDescendantIds(
    id
  ) {
    const ids = [];

    function collect(
      parentId
    ) {
      childrenOf(
        parentId
      ).forEach(
        (entry) => {
          ids.push(
            entry.id
          );

          if (
            expandedNodes.has(
              entry.id
            )
          ) {
            collect(
              entry.id
            );
          }
        }
      );
    }

    collect(id);

    return ids;
  }

  function collapseDescendants(
    id
  ) {
    childrenOf(
      id
    ).forEach(
      (entry) => {
        expandedNodes.delete(
          entry.id
        );

        collapseDescendants(
          entry.id
        );
      }
    );
  }

  function animateBranchOpening(
    revealedIds
  ) {
    if (
      !revealedIds.length ||
      !(
        "animate" in
        Element.prototype
      )
    ) {
      return;
    }

    window.requestAnimationFrame(
      () => {
        revealedIds.forEach(
          (id, index) => {
            const entry =
              entryById(id);

            const parent =
              entry?.parentId
                ? entryById(
                  entry.parentId
                )
                : null;

            const node =
              nodes.querySelector(
                `[data-entry-id="${id}"]`
              );

            if (
              !entry ||
              !parent ||
              !node
            ) {
              return;
            }

            node.animate(
              [
                {
                  left:
                    `${parent.x}%`,
                  top:
                    `${parent.y}%`,
                  opacity: 0,
                  filter:
                    "blur(4px)",
                },
                {
                  left:
                    `${entry.x}%`,
                  top:
                    `${entry.y}%`,
                  opacity: 1,
                  filter:
                    "blur(0)",
                },
              ],
              {
                duration: 440,
                delay:
                  40 +
                  index * 55,
                easing:
                  "cubic-bezier(.22, 1, .36, 1)",
                fill:
                  "backwards",
              }
            );
          }
        );

        const revealedSet =
          new Set(
            revealedIds
          );

        lines
          .querySelectorAll(
            "line"
          )
          .forEach(
            (line) => {
              if (
                !revealedSet.has(
                  line.dataset
                    .from
                ) &&
                !revealedSet.has(
                  line.dataset
                    .to
                )
              ) {
                return;
              }

              const finalOpacity =
                getComputedStyle(
                  line
                ).opacity;

              line.animate(
                [
                  {
                    opacity: 0,
                    strokeDasharray:
                      "1 1",
                    strokeDashoffset:
                      "1",
                  },
                  {
                    opacity:
                      finalOpacity,
                    strokeDasharray:
                      "1 1",
                    strokeDashoffset:
                      "0",
                  },
                ],
                {
                  duration: 380,
                  delay: 55,
                  easing:
                    "cubic-bezier(.22, 1, .36, 1)",
                }
              );
            }
          );
      }
    );
  }

  async function animateBranchClosing(
    id
  ) {
    const closingIds =
      new Set(
        visibleDescendantIds(
          id
        )
      );

    if (
      !closingIds.size
    ) {
      return;
    }

    if (
      !(
        "animate" in
        Element.prototype
      )
    ) {
      return;
    }

    const nodeAnimations =
      Array.from(
        nodes.querySelectorAll(
          ".life-node"
        )
      )
        .filter(
          (node) =>
            closingIds.has(
              node.dataset
                .entryId
            )
        )
        .map(
          (node, index) => {
            const entry =
              entryById(
                node.dataset
                  .entryId
              );

            const parent =
              entry?.parentId
                ? entryById(
                  entry.parentId
                )
                : null;

            if (
              !entry ||
              !parent
            ) {
              return Promise.resolve();
            }

            return node
              .animate(
                [
                  {
                    left:
                      `${entry.x}%`,
                    top:
                      `${entry.y}%`,
                    opacity: 1,
                    filter:
                      "blur(0)",
                  },
                  {
                    left:
                      `${parent.x}%`,
                    top:
                      `${parent.y}%`,
                    opacity: 0,
                    filter:
                      "blur(4px)",
                  },
                ],
                {
                  duration: 330,
                  delay:
                    index * 25,
                  easing:
                    "cubic-bezier(.4, 0, .6, 1)",
                  fill:
                    "forwards",
                }
              )
              .finished
              .catch(
                () => { }
              );
          }
        );

    const lineAnimations =
      Array.from(
        lines.querySelectorAll(
          "line"
        )
      )
        .filter(
          (line) =>
            closingIds.has(
              line.dataset.from
            ) ||
            closingIds.has(
              line.dataset.to
            )
        )
        .map(
          (line) => {
            const currentOpacity =
              getComputedStyle(
                line
              ).opacity;

            return line
              .animate(
                [
                  {
                    opacity:
                      currentOpacity,
                    strokeDasharray:
                      "1 1",
                    strokeDashoffset:
                      "0",
                  },
                  {
                    opacity: 0,
                    strokeDasharray:
                      "1 1",
                    strokeDashoffset:
                      "1",
                  },
                ],
                {
                  duration: 280,
                  easing:
                    "cubic-bezier(.4, 0, .6, 1)",
                  fill:
                    "forwards",
                }
              )
              .finished
              .catch(
                () => { }
              );
          }
        );

    await Promise.all([
      ...nodeAnimations,
      ...lineAnimations,
    ]);
  }

  function updateFocus() {
    const entry =
      entryById(
        activeId
      );

    if (!entry) {
      return;
    }

    world.style.transform =
      `translate(` +
      `calc(${50 /
      GRAPH_WIDTH_SCALE -
      entry.x
      }% + ${pan.x}px), ` +
      `calc(${50 /
      GRAPH_HEIGHT_SCALE -
      entry.y
      }% + ${pan.y}px)` +
      `)`;

    nodes
      .querySelectorAll(
        ".life-node"
      )
      .forEach(
        (node) => {
          const isActive =
            node.dataset
              .entryId ===
            activeId;

          node.classList.toggle(
            "is-active",
            isActive
          );

          node.setAttribute(
            "aria-pressed",
            String(
              isActive
            )
          );
        }
      );

    lines
      .querySelectorAll(
        "line"
      )
      .forEach(
        (line) => {
          const connected =
            line.dataset.from ===
            activeId ||
            line.dataset.to ===
            activeId;

          line.classList.toggle(
            "is-connected",
            connected
          );
        }
      );
  }

  function renderGraph(
    revealedIds = []
  ) {
    const entries =
      visibleEntries();

    const visibleIds =
      new Set(
        entries.map(
          (entry) =>
            entry.id
        )
      );

    lines.innerHTML =
      visualEdges
        .filter(
          ({
            fromId,
            toId,
          }) =>
            visibleIds.has(
              fromId
            ) &&
            visibleIds.has(
              toId
            )
        )
        .map(
          ({
            fromId,
            toId,
            kind,
          }) => {
            const from =
              entryById(
                fromId
              );

            const to =
              entryById(
                toId
              );

            return `
              <line
                data-from="${fromId}"
                data-to="${toId}"
                class="is-${kind}"
                pathLength="1"
                x1="${from.x}"
                y1="${from.y}"
                x2="${to.x}"
                y2="${to.y}"
              ></line>
            `;
          }
        )
        .join("");

    nodes.innerHTML =
      entries
        .map(
          (
            entry,
            index
          ) => {
            const expandable =
              hasChildren(
                entry.id
              );

            const expanded =
              expandedNodes.has(
                entry.id
              );

            const nodeType =
              !entry.parentId ||
                expandable
                ? "life-node-main"
                : "life-node-child";

            return `
              <button
                class="life-node ${nodeType}${entry.id ===
                activeId
                ? " is-active"
                : ""
              }"
                type="button"
                data-entry-id="${entry.id}"
                aria-pressed="${entry.id ===
              activeId
              }"
                ${expandable
                ? `aria-expanded="${expanded}"`
                : ""
              }
                style="
                  left:${entry.x}%;
                  top:${entry.y}%;
                  --float-delay:${index * -0.73
              }s
                "
              >
                <span
                  class="life-node-dot"
                  aria-hidden="true"
                ></span>

                <span>
                  ${entry.label}
                </span>
              </button>
            `;
          }
        )
        .join("");

    updateFocus();

    animateBranchOpening(
      revealedIds
    );
  }

  function updateStory() {
    const entry =
      entryById(
        activeId
      );

    if (!entry) {
      return;
    }

    storySlot.innerHTML =
      storyMarkup(
        entry,
        true
      );

    activateGallery(
      storySlot.querySelector(
        ".about-story"
      ),
      entry
    );
  }

  function scrollToStoryOnMobile() {
    if (
      !window.matchMedia(
        "(max-width: 650px)"
      ).matches
    ) {
      return;
    }

    const story =
      storySlot.querySelector(
        ".about-story"
      );

    if (!story) {
      return;
    }

    window.requestAnimationFrame(
      () => {
        story.scrollIntoView({
          behavior: "smooth",
          block: "start",
        });
      }
    );
  }

  nodes.addEventListener(
    "click",
    async (event) => {
      const node =
        event.target.closest(
          "button[data-entry-id]"
        );

      if (
        !node ||
        suppressClick ||
        branchAnimationRunning
      ) {
        return;
      }

      const id =
        node.dataset
          .entryId;

      const expandable =
        hasChildren(id);

      let revealedIds = [];

      activeId = id;

      pan = {
        x: 0,
        y: 0,
      };

      if (expandable) {
        if (
          expandedNodes.has(
            id
          )
        ) {
          branchAnimationRunning =
            true;

          updateFocus();
          updateStory();

          await animateBranchClosing(
            id
          );

          expandedNodes.delete(
            id
          );

          collapseDescendants(
            id
          );

          renderGraph();

          branchAnimationRunning =
            false;
        } else {
          expandedNodes.add(
            id
          );

          revealedIds =
            childrenOf(id).map(
              (entry) =>
                entry.id
            );

          renderGraph(
            revealedIds
          );

          updateStory();
        }
      } else {
        updateFocus();
        updateStory();
      }

      if (!expandable) {
        scrollToStoryOnMobile();
      }
    }
  );

  graph.addEventListener(
    "pointerdown",
    (event) => {
      if (
        event.button !== 0
      ) {
        return;
      }

      drag = {
        pointerId:
          event.pointerId,

        startX:
          event.clientX,

        startY:
          event.clientY,

        panX:
          pan.x,

        panY:
          pan.y,

        moved:
          false,
      };

      graph.classList.add(
        "is-dragging"
      );
    }
  );

  graph.addEventListener(
    "pointermove",
    (event) => {
      if (
        !drag ||
        drag.pointerId !==
        event.pointerId
      ) {
        return;
      }

      const deltaX =
        event.clientX -
        drag.startX;

      const deltaY =
        event.clientY -
        drag.startY;

      if (
        !drag.moved &&
        Math.abs(deltaX) +
        Math.abs(deltaY) >
        10
      ) {
        drag.moved = true;

        graph.setPointerCapture(
          event.pointerId
        );
      }

      if (!drag.moved) {
        return;
      }

      const maxX =
        graph.clientWidth *
        0.55;

      const maxY =
        graph.clientHeight *
        0.5;

      pan = {
        x: Math.max(
          -maxX,
          Math.min(
            maxX,
            drag.panX +
            deltaX
          )
        ),

        y: Math.max(
          -maxY,
          Math.min(
            maxY,
            drag.panY +
            deltaY
          )
        ),
      };

      updateFocus();
    }
  );

  function stopDrag(event) {
    if (
      !drag ||
      drag.pointerId !==
      event.pointerId
    ) {
      return;
    }

    if (
      graph.hasPointerCapture(
        event.pointerId
      )
    ) {
      graph.releasePointerCapture(
        event.pointerId
      );
    }

    if (drag.moved) {
      suppressClick = true;

      window.setTimeout(
        () => {
          suppressClick =
            false;
        },
        0
      );
    }

    drag = null;

    graph.classList.remove(
      "is-dragging"
    );
  }

  graph.addEventListener(
    "pointerup",
    stopDrag
  );

  graph.addEventListener(
    "pointercancel",
    stopDrag
  );

  renderGraph();
  updateStory();
}

